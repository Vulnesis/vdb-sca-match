// TestParseRequirementsTxtScoped_ViaBlock exercises the trailing "# via"
// annotation rule from parseRequirementsTxtScoped's doc comment: an include
// (-r/-c) marks the package as direct; only parent packages mark it as
// transitive; mixed lists are direct because the include wins.
func TestParseRequirementsTxtScoped_ViaBlock(t *testing.T) {
	cases := []struct {
		name string
		data string
		want map[string]bool
	}{
		{
			name: "via include keeps IsDirect true",
			data: "requests==2.31.0\n    # via -r base.in\n",
			want: map[string]bool{"requests": true},
		},
		{
			name: "via parent package sets IsDirect false",
			data: "certifi==2024.2.2\n    # via requests\n",
			want: map[string]bool{"certifi": false},
		},
		{
			name: "via list with include and parent is direct",
			data: "idna==3.6\n    # via -r base.in, requests\n",
			want: map[string]bool{"idna": true},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			pkgs, err := parseRequirementsTxtScoped([]byte(tc.data), "requirements.txt")
			if err != nil {
				t.Fatal(err)
			}
			got := map[string]bool{}
			for _, p := range pkgs {
				got[p.Name] = p.IsDirect
			}
			for n, wantDirect := range tc.want {
				if got[n] != wantDirect {
					t.Errorf("%s IsDirect=%v, want %v (got=%v)", n, got[n], wantDirect, got)
				}
			}
		})
	}
}

// TestParseRequirementsTxtScoped_HashesAndContinuations covers the hash
// accumulation, backslash continuation joining, inline/stanza comment
// stripping, and editable VCS requirements documented for
// parseRequirementsTxtScoped.
func TestParseRequirementsTxtScoped_HashesAndContinuations(t *testing.T) {
	sha256A := strings.Repeat("a", 64)
	sha256B := strings.Repeat("b", 64)
	sha1A := strings.Repeat("c", 40)

	cases := []struct {
		name           string
		data           string
		wantNames      []string
		wantChecksums  int
		wantAlg        string
		wantVersion    string
		wantDirectness map[string]bool
	}{
		{
			name:      "inline comment stripped and hashes accumulated",
			data:      "requests==2.31.0 --hash=sha256:" + sha256A + " --hash=sha1:" + sha1A + " # pinned\n",
			wantNames: []string{"requests"}, wantChecksums: 2,
			wantVersion: "2.31.0",
		},
		{
			name:      "backslash continuation joins hash line",
			data:      "requests==2.31.0 \\\n    --hash=sha256:" + sha256A + " \\\n    --hash=sha256:" + sha256B + "\n",
			wantNames: []string{"requests"}, wantChecksums: 2,
		},
		{
			name:      "leading comment ignored before any package",
			data:      "# This file is autogenerated\nrequests==2.31.0\n",
			wantNames: []string{"requests"}, wantChecksums: 0,
		},
		{
			name:           "editable VCS requirement yields direct pypi package",
			data:           "-e git+https://github.com/psf/requests.git#egg=requests\n",
			wantNames:      []string{"requests"},
			wantDirectness: map[string]bool{"requests": true},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			pkgs, err := parseRequirementsTxtScoped([]byte(tc.data), "requirements.txt")
			if err != nil {
				t.Fatal(err)
			}
			gotNames := map[string]struct{}{}
			for _, p := range pkgs {
				gotNames[p.Name] = struct{}{}
				if tc.wantVersion != "" && p.Name == tc.wantNames[0] && p.Version != tc.wantVersion {
					t.Errorf("%s version=%q, want %q", p.Name, p.Version, tc.wantVersion)
				}
				if tc.wantChecksums != 0 && len(p.Checksums) != tc.wantChecksums {
					t.Errorf("%s checksum count=%d, want %d", p.Name, len(p.Checksums), tc.wantChecksums)
				}
				if want, ok := tc.wantDirectness[p.Name]; ok && p.IsDirect != want {
					t.Errorf("%s IsDirect=%v, want %v", p.Name, p.IsDirect, want)
				}
			}
			for _, n := range tc.wantNames {
				if _, ok := gotNames[n]; !ok {
					t.Errorf("package %q not found", n)
				}
			}
		})
	}
}

// TestParsePipfileLockScoped confirms that [default] maps to production,
// [develop] maps to development, hashes are normalised, and invalid JSON
// returns an error.
func TestParsePipfileLockScoped(t *testing.T) {
	src := []byte(`{
  "default": {
    "requests": {"version": "==2.31.0", "hashes": ["sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"]}
  },
  "develop": {
    "pytest": {"version": "==8.0.0", "hashes": ["sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"]}
  }
}`)
	pkgs, err := parsePipfileLockScoped(src, "Pipfile.lock")
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]struct{ scope, alg string }{}
	for _, p := range pkgs {
		alg := ""
		if len(p.Checksums) > 0 {
			alg = p.Checksums[0].Alg
		}
		got[p.Name] = struct{ scope, alg string }{p.Scope, alg}
	}
	if got["requests"].scope != ScopeProduction {
		t.Errorf("requests scope=%q, want production", got["requests"].scope)
	}
	if got["pytest"].scope != ScopeDevelopment {
		t.Errorf("pytest scope=%q, want development", got["pytest"].scope)
	}
	if got["requests"].alg != "SHA-256" {
		t.Errorf("requests alg=%q, want SHA-256", got["requests"].alg)
	}

	_, err = parsePipfileLockScoped([]byte("not json"), "Pipfile.lock")
	if err == nil {
		t.Error("invalid JSON: expected error, got nil")
	}
}

// TestParseUVLockScoped confirms that [[package]] entries with sdist and
// wheels yield one pypi ScopedPackage carrying every hash, empty-name entries
// are skipped, and malformed TOML errors.
func TestParseUVLockScoped(t *testing.T) {
	src := []byte(`[[package]]
name = "requests"
version = "2.31.0"
sdist = { url = "https://example.com/requests-2.31.0.tar.gz", hash = "sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa" }
wheels = [
  { url = "https://example.com/requests-2.31.0-py3-none-any.whl", hash = "sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb" },
]

[[package]]
version = "3.0.0"
`)
	pkgs, err := parseUVLockScoped(src, "uv.lock")
	if err != nil {
		t.Fatal(err)
	}
	if len(pkgs) != 1 {
		t.Fatalf("got %d packages, want 1", len(pkgs))
	}
	p := pkgs[0]
	if p.Name != "requests" || p.Version != "2.31.0" || p.Ecosystem != "pypi" || p.Scope != ScopeProduction {
		t.Errorf("package=%+v", p)
	}
	if len(p.Checksums) != 2 {
		t.Fatalf("checksum count=%d, want 2", len(p.Checksums))
	}
	for _, c := range p.Checksums {
		if c.Alg != "SHA-256" {
			t.Errorf("unexpected alg %q", c.Alg)
		}
	}

	_, err = parseUVLockScoped([]byte("not [toml"), "uv.lock")
	if err == nil {
		t.Error("malformed TOML: expected error, got nil")
	}
}

// TestParsePylockTOMLScoped confirms that PEP 751 sdist/wheels sub-table
// hashes become PackageChecksum entries for each algorithm.
func TestParsePylockTOMLScoped(t *testing.T) {
	src := []byte(`version = "1.0"

[[packages]]
name = "requests"
version = "2.31.0"
sdist = { url = "https://example.com/requests-2.31.0.tar.gz", hashes = { sha256 = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa", sha512 = "eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee", sha1 = "cccccccccccccccccccccccccccccccccccccccc" } }
wheels = [
  { url = "https://example.com/requests-2.31.0-py3-none-any.whl", hashes = { sha256 = "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb" } },
]
`)
	pkgs, err := parsePylockTOMLScoped(src, "pylock.toml")
	if err != nil {
		t.Fatal(err)
	}
	if len(pkgs) != 1 {
		t.Fatalf("got %d packages, want 1", len(pkgs))
	}
	p := pkgs[0]
	if p.Name != "requests" {
		t.Errorf("name=%q, want requests", p.Name)
	}
	wantAlgs := map[string]bool{"SHA-256": true, "SHA-512": true, "SHA-1": true}
	gotAlgs := map[string]int{}
	for _, c := range p.Checksums {
		gotAlgs[c.Alg]++
	}
	for alg := range wantAlgs {
		if gotAlgs[alg] == 0 {
			t.Errorf("missing alg %q", alg)
		}
	}
}

// TestParseGoModScoped confirms both single-line `require x v1.2.3` and block
// `require (...) ` forms produce direct golang packages with the leading "v"
// stripped from the version.
func TestParseGoModScoped(t *testing.T) {
	src := []byte(`module example.com/app

go 1.22

require github.com/pkg/errors v0.9.1

require (
	github.com/spf13/cobra v1.8.0
	// ignored comment
)
`)
	pkgs, err := parseGoModScoped(src, "go.mod")
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]string{
		"github.com/pkg/errors":  "0.9.1",
		"github.com/spf13/cobra": "1.8.0",
	}
	got := map[string]string{}
	for _, p := range pkgs {
		got[p.Name] = p.Version
		if p.Ecosystem != "golang" || p.Scope != ScopeProduction || !p.IsDirect {
			t.Errorf("package=%+v", p)
		}
	}
	for n, v := range want {
		if got[n] != v {
			t.Errorf("%s: version=%q, want %q", n, got[n], v)
		}
	}
}
