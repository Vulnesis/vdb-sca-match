// ── package.json ────────────────────────────────────────────────────────────

// A dependency on another workspace member, or on a path, is not a registry
// package. "workspace:*" passes as a pinned spec, so it was queried under the
// member's own name.
func TestPackageJSON_LocalSpecsAreNotPackages(t *testing.T) {
	const manifest = `{
  "dependencies": {"express": "^4.21.0", "lib": "workspace:*", "lib2": "workspace:^1.0.0", "vendored": "file:../vendored"},
  "devDependencies": {"linked": "link:../linked", "portal": "portal:../p", "jest": "29.0.0"}
}`
	pkgs, err := ParseManifest([]byte(manifest), "package.json", "package.json")
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, p := range pkgs {
		names = append(names, p.Name)
	}
	sort.Strings(names)
	if strings.Join(names, ",") != "express,jest" {
		t.Errorf("packages = %v, want express,jest", names)
	}
}
