// Regression tests for the JavaScript lockfiles: npm (package-lock.json), yarn
// Classic and Berry (yarn.lock), pnpm v5/v6/v9 (pnpm-lock.yaml) and bun
// (bun.lock). Every package manager gets the same questions: does it read the
// lock its current release writes, are workspace members (source in the
// repository, never a registry release) kept out, and are the dependencies a
// workspace declares marked direct. Vulnesis/cli#177: a bun monorepo was not
// read at all, and the lock of every npm-family monorepo lists the members.

type pkgIndex map[string]ScopedPackage

func index(t *testing.T, pkgs []ScopedPackage) pkgIndex {
	t.Helper()
	out := pkgIndex{}
	for _, p := range pkgs {
		id := p.Name + "@" + p.Version
		if _, dup := out[id]; dup {
			t.Errorf("duplicate package %s", id)
		}
		if p.Ecosystem != "npm" {
			t.Errorf("%s: ecosystem %q, want npm", id, p.Ecosystem)
		}
		out[id] = p
	}
	return out
}

func (ix pkgIndex) direct() []string {
	var out []string
	for id, p := range ix {
		if p.IsDirect {
			out = append(out, id)
		}
	}
	sort.Strings(out)
	return out
}

func mustParse(t *testing.T, manifestType, data string) pkgIndex {
	t.Helper()
	pkgs, err := ParseManifest([]byte(data), manifestType, manifestType)
	if err != nil {
		t.Fatalf("ParseManifest(%s): %v", manifestType, err)
	}
	return index(t, pkgs)
}

func wantIDs(t *testing.T, ix pkgIndex, ids ...string) {
	t.Helper()
	var got []string
	for id := range ix {
		got = append(got, id)
	}
	sort.Strings(got)
	sort.Strings(ids)
	if strings.Join(got, " ") != strings.Join(ids, " ") {
		t.Errorf("packages:\n got  %v\n want %v", got, ids)
	}
}

func wantScope(t *testing.T, ix pkgIndex, id, scope string) {
	t.Helper()
	p, ok := ix[id]
	if !ok {
		t.Errorf("%s missing", id)
		return
	}
	if p.Scope != scope {
		t.Errorf("%s scope %q, want %q", id, p.Scope, scope)
	}
}

// ── Real lockfiles written by each package manager ──────────────────────────

// The same monorepo (a root, packages/app and tools/fixed-point, five registry
// dependencies between them and one workspace-to-workspace dependency) installed
// by each package manager. Generated by bun 1.4, npm 11, pnpm 11 and yarn 4.
func TestWorkspaceLockfiles_EveryPackageManager(t *testing.T) {
	cases := []struct {
		pm, file, manifestType string
	}{
		{"bun", "bun.lock", "bun.lock"},
		{"npm", "package-lock.json", "package-lock.json"},
		{"pnpm", "pnpm-lock.yaml", "pnpm-lock.yaml"},
		{"yarn", "yarn.lock", "yarn.lock"},
	}
	wantDirect := []string{"axios", "chalk", "dotenv", "express", "lodash"}
	for _, c := range cases {
		t.Run(c.pm, func(t *testing.T) {
			data, err := os.ReadFile(filepath.Join("testdata", "workspaces", c.pm, c.file))
			if err != nil {
				t.Fatal(err)
			}
			pkgs, err := ParseManifest(data, c.manifestType, c.file)
			if err != nil {
				t.Fatal(err)
			}
			ix := index(t, pkgs)
			if len(ix) < 80 {
				t.Errorf("%d packages, want the whole installed tree (80+)", len(ix))
			}
			var directNames []string
			for _, id := range ix.direct() {
				directNames = append(directNames, ix[id].Name)
			}
			if strings.Join(directNames, ",") != strings.Join(wantDirect, ",") {
				t.Errorf("direct = %v, want %v (the root's and every member's declared dependencies)", directNames, wantDirect)
			}
			for id, p := range ix {
				if p.Name == "app" || p.Name == "fixed-point" || strings.HasSuffix(p.Name, "workspace-test") {
					t.Errorf("workspace member emitted as a registry package: %s", id)
				}
				if !registryVersion(p.Version) {
					t.Errorf("%s: version is not a release", id)
				}
				if c.pm != "yarn" && len(p.Checksums) == 0 {
					// Berry's checksum hashes its own zip, not the npm tarball.
					t.Errorf("%s: integrity dropped", id)
				}
			}
		})
	}
}

