// ── package-lock.json ───────────────────────────────────────────────────────

func TestPackageLock_V3Workspaces(t *testing.T) {
	const lock = `{
  "lockfileVersion": 3,
  "packages": {
    "": {"name": "root", "workspaces": ["packages/*"], "dependencies": {"debug": "^4"}},
    "packages/app": {"name": "app", "version": "0.1.0", "dependencies": {"debug": "^2", "ms": "^2"}, "devDependencies": {"jest": "^29"}},
    "node_modules/app": {"resolved": "packages/app", "link": true},
    "node_modules/debug": {"version": "4.3.4", "integrity": "sha512-AAAA", "dependencies": {"ms": "2.1.2"}},
    "node_modules/ms": {"version": "2.1.2", "integrity": "sha512-BBBB"},
    "packages/app/node_modules/debug": {"version": "2.6.9", "integrity": "sha512-CCCC"},
    "node_modules/debug/node_modules/@s/inner": {"version": "1.0.0"},
    "node_modules/jest": {"version": "29.0.0", "dev": true},
    "node_modules/aliased": {"name": "real-pkg", "version": "3.0.0"},
    "node_modules/gitdep": {"version": "git+ssh://git@github.com/o/r.git#abc", "resolved": "git+ssh://git@github.com/o/r.git#abc"}
  }
}`
	ix := mustParse(t, "package-lock.json", lock)
	// Two versions of debug both survive; the nested path is named by its last
	// segment; the member directory and its symlink are not packages.
	wantIDs(t, ix, "debug@4.3.4", "debug@2.6.9", "ms@2.1.2", "@s/inner@1.0.0", "jest@29.0.0", "real-pkg@3.0.0")
	// The root declares debug (hoisted 4.3.4); the member declares debug (its own
	// nested 2.6.9), ms (hoisted) and jest.
	if got := strings.Join(ix.direct(), " "); got != "debug@2.6.9 debug@4.3.4 jest@29.0.0 ms@2.1.2" {
		t.Errorf("direct = %s", got)
	}
	wantScope(t, ix, "jest@29.0.0", ScopeDevelopment)
}

