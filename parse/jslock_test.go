func TestPnpmLock_V9(t *testing.T) {
	const lock = `lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      react-dom:
        specifier: ^18
        version: 18.2.0(react@18.2.0)
    devDependencies:
      vitest:
        specifier: ^1
        version: 1.0.0

  packages/lib:
    dependencies:
      '@s/x':
        specifier: ^1
        version: 1.0.0
      app:
        specifier: workspace:*
        version: link:../app

packages:

  '@s/x@1.0.0':
    resolution: {integrity: sha512-AAAA}

  react-dom@18.2.0:
    resolution: {integrity: sha512-BBBB}
    peerDependencies:
      react: ^18

  react@18.2.0:
    resolution: {integrity: sha512-CCCC}

  vitest@1.0.0:
    resolution: {integrity: sha512-DDDD}

  tinyspy@2.0.0:
    resolution: {integrity: sha512-EEEE}

  gitpkg@https://codeload.github.com/o/r/tar.gz/abc:
    resolution: {tarball: https://codeload.github.com/o/r/tar.gz/abc}
    name: gitpkg
    version: 1.0.0

snapshots:

  '@s/x@1.0.0': {}

  react-dom@18.2.0(react@18.2.0):
    dependencies:
      react: 18.2.0

  react@18.2.0: {}

  vitest@1.0.0:
    dependencies:
      tinyspy: 2.0.0
`
	ix := mustParse(t, "pnpm-lock.yaml", lock)
	wantIDs(t, ix, "@s/x@1.0.0", "react-dom@18.2.0", "react@18.2.0", "vitest@1.0.0", "tinyspy@2.0.0")
	if got := strings.Join(ix.direct(), " "); got != "@s/x@1.0.0 react-dom@18.2.0 vitest@1.0.0" {
		t.Errorf("direct = %s", got)
	}
	// v9 has no dev flag: the scope comes from the importers through the snapshots.
	wantScope(t, ix, "tinyspy@2.0.0", ScopeDevelopment)
	wantScope(t, ix, "react@18.2.0", ScopeProduction)
	if c := ix["react@18.2.0"].Checksums; len(c) != 1 {
		t.Errorf("inline integrity not read: %+v", c)
	}
}

